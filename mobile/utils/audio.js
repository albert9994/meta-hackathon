import * as Speech from 'expo-speech';

/**
 * VibeRide - In-Ear Audio Co-Pilot & Safety Advisory Engine
 *
 * Implements:
 * 1. Hands-free audio cues for turn-by-turn guidance and route intros.
 * 2. High-priority audio interrupt for edge Spatial Safety Sensor hazard alerts.
 * 3. Consistent voice pitch and speech rate tuned for clear in-ear audio during urban riding.
 * 4. English voice synthesis (en-US / en-GB).
 */

// Global state for mute toggle and speech queue control
let isAudioMuted = false;

// Default audio settings: clear, calm, steady pace for cycling
const DEFAULT_SPEECH_OPTIONS = {
  language: 'en-US',
  pitch: 1.0,
  rate: 0.95, // Slightly slower than natural speech for clarity over ambient wind/traffic
};

/**
 * Core internal wrapper for expo-speech with error handling and mute checks.
 */
async function speakText(text, customOptions = {}) {
  if (!text || isAudioMuted) {
    return;
  }

  try {
    const isSpeaking = await Speech.isSpeakingAsync();
    // If something is already playing and priority is requested, stop previous audio
    if (isSpeaking && customOptions.interrupt) {
      await Speech.stop();
    }

    const options = {
      ...DEFAULT_SPEECH_OPTIONS,
      ...customOptions,
    };

    Speech.speak(text, options);
  } catch (error) {
    console.warn('[VibeRide Audio] Speech synthesis error:', error);
  }
}

/**
 * Plays the initial semantic route overview generated by the AI (audio_intro).
 * Example: "Route ready. Navigating through calm residential streets and green canopies."
 */
export async function playRouteIntro(audioIntro) {
  if (!audioIntro) return;

  await speakText(audioIntro, {
    interrupt: true,
    pitch: 1.05,
    rate: 0.92,
  });
}

/**
 * Plays navigational cues and waypoint arrival announcements.
 * Example: "In 100 meters, turn left onto Strada Dr. Joseph Lister."
 */
export async function playNavigationCue(cueText) {
  if (!cueText) return;

  await speakText(cueText, {
    interrupt: false, // Allows natural completion unless an alert interrupts
    rate: 0.95,
  });
}

/**
 * Plays an immediate Spatial Safety Sensor hazard alert (audio_alert).
 * Interrupts any ongoing background speech or navigation cue instantly.
 * Example: "Caution: Uneven cobblestone and slick tram tracks ahead. Slow down."
 */
export async function playSafetyAlert(audioAlert) {
  if (!audioAlert) return;

  // Immediate interrupt for rider safety
  await speakText(audioAlert, {
    interrupt: true,
    pitch: 1.15, // Slightly higher pitch to stand out through ambient street noise
    rate: 1.0,   // Immediate delivery
  });
}

/**
 * Stops any active speech playback immediately.
 */
export async function stopAllAudio() {
  try {
    await Speech.stop();
  } catch (error) {
    console.warn('[VibeRide Audio] Error stopping speech:', error);
  }
}

/**
 * Sets or toggles the mute state of the audio co-pilot.
 */
export function setAudioMute(muted) {
  isAudioMuted = Boolean(muted);
  if (isAudioMuted) {
    Speech.stop();
  }
}

/**
 * Returns current mute state.
 */
export function getAudioMuteState() {
  return isAudioMuted;
}